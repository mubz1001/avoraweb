import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import react from '@vitejs/plugin-react';
import type { Plugin } from 'vite';
import { defineConfig } from 'vitest/config';

/** Content-Security-Policy for production builds (the dev server needs inline scripts for HMR). Header-only
 *  directives such as frame-ancestors belong in the host's response headers; see docs/04. */
const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "worker-src 'self'",
  'frame-src https://www.google.com',
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join('; ');

const csp = (): Plugin => ({
  name: 'avora-csp',
  apply: 'build',
  transformIndexHtml: (html) =>
    html.replace(
      '<meta charset="utf-8" />',
      `<meta charset="utf-8" />
    <meta http-equiv="Content-Security-Policy" content="${CSP}" />`,
    ),
});

/** The public address of the site, for canonical and share-card URLs (they must be absolute). Set VITE_SITE_URL for the
 *  real domain; robots.txt and sitemap.xml use it too. */
const SITE_URL = (process.env.VITE_SITE_URL ?? 'https://avorabookings.com').replace(/\/$/, '');

const PUBLIC_PAGES = ['', '/search', '/support', '/legal/terms', '/legal/privacy'];

/** Fills `__SITE_URL__` in index.html, and writes robots.txt and sitemap.xml at build (stays come from the mock
 *  catalogue; with a real API the sitemap should be generated by the backend). */
const seo = (): Plugin => ({
  name: 'avora-seo',
  transformIndexHtml: (html) => html.replaceAll('__SITE_URL__', SITE_URL),
  generateBundle() {
    const stays = (JSON.parse(readFileSync('src/mocks/data/properties.json', 'utf8')) as { id: string }[]).map(
      (p) => `/stays/${encodeURIComponent(p.id)}`,
    );
    const urls = [...PUBLIC_PAGES, ...stays].map((p) => `  <url><loc>${SITE_URL}${p || '/'}</loc></url>`);
    const sitemap = [
      '<?xml version="1.0" encoding="UTF-8"?>',
      '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
      ...urls,
      '</urlset>',
      '',
    ];
    const robots = [
      'User-agent: *',
      'Allow: /',
      'Disallow: /account',
      'Disallow: /checkout',
      'Disallow: /orders/',
      'Disallow: /bookings/',
      'Disallow: /signin',
      'Disallow: /signup',
      'Disallow: /forgot-password',
      'Disallow: /reset-password',
      `Sitemap: ${SITE_URL}/sitemap.xml`,
      '',
    ];
    this.emitFile({ type: 'asset', fileName: 'sitemap.xml', source: sitemap.join('\n') });
    this.emitFile({ type: 'asset', fileName: 'robots.txt', source: robots.join('\n') });
  },
});

export default defineConfig({
  plugins: [react(), csp(), seo()],
  resolve: { alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) } },
  server: { port: 5173, strictPort: true },
  preview: { port: 5173, strictPort: true },
  test: {
    environment: 'jsdom',
    globals: true,
    setupFiles: ['tests/setup.ts'],
    include: ['src/**/*.test.{ts,tsx}'],
  },
});
